import React, { useMemo, useState } from 'react';
import TurkeyMapCore from 'turkey-map-react/core';
import { geoJsonToCities } from 'turkey-map-react/geojson';
import sampleGeoJson from './sampleGeoJson';

const MAPPINGS = {
  default: {
    label: 'Default properties',
    keys: {
      idKey: 'id',
      nameKey: 'name',
      plateKey: 'plateNumber',
    },
  },
  custom: {
    label: 'Custom ADM1 properties',
    keys: {
      idKey: 'ADM1_CODE',
      nameKey: 'NAME_1',
      plateKey: 'PLATE',
    },
  },
  accessor: {
    label: 'Accessor functions',
    keys: {
      idKey: (properties) => String(properties.ADM1_CODE ?? properties.id).toLowerCase(),
      nameKey: (properties) => properties.NAME_1 ?? properties.name,
      plateKey: (properties) => Number(properties.PLATE ?? properties.plateNumber) || 0,
    },
  },
};

const PROJECTIONS = {
  default: {
    label: 'Default equirectangular',
    project: undefined,
  },
  mercator: {
    label: 'Mercator-ish projection',
    project: (lon, lat) => {
      const x = (lon * Math.PI) / 180;
      const y = -Math.log(Math.tan(Math.PI / 4 + ((lat * Math.PI) / 180) / 2));
      return [x, y];
    },
  },
};

const countSubpaths = (path) => (path.match(/M /g) || []).length;

const formatKey = (key) => (typeof key === 'string' ? `'${key}'` : '(properties) => …');

function GeojsonScenario() {
  const [mapping, setMapping] = useState('default');
  const [projection, setProjection] = useState('default');
  const [padding, setPadding] = useState(20);
  const [precision, setPrecision] = useState(4);
  const [includeUnsupported, setIncludeUnsupported] = useState(true);
  const [selectedId, setSelectedId] = useState('marmara');

  const collection = useMemo(() => {
    if (includeUnsupported) return sampleGeoJson;
    return {
      ...sampleGeoJson,
      features: sampleGeoJson.features.filter((feature) => feature.geometry.type !== 'Point'),
    };
  }, [includeUnsupported]);

  const converted = useMemo(() => (
    geoJsonToCities(collection, {
      ...MAPPINGS[mapping].keys,
      project: PROJECTIONS[projection].project,
      padding,
      precision,
    })
  ), [collection, mapping, projection, padding, precision]);

  const data = useMemo(() => ({ cities: converted }), [converted]);
  const skipped = collection.features.length - converted.length;
  const selectedCity = converted.find((city) => city.id === selectedId) || converted[0] || null;

  const renderTooltip = (city) => (
    <span className="tooltip-card">
      <span className="chroma-tooltip-top">
        <span className="tooltip-plate">{String(city.plateNumber).padStart(2, '0')}</span>
        <span className="chroma-tooltip-scale">{mapping}</span>
      </span>
      <strong className="tooltip-card-name">{city.name}</strong>
      <span className="tooltip-card-meta">
        id: {city.id}
        {' · '}
        {countSubpaths(city.path)}
        {' '}
        subpaths
      </span>
      <span className="tooltip-card-hint">Generated by geoJsonToCities</span>
    </span>
  );

  return (
    <div className="map-grid">
      <div className="map-card">
        <div className="map-header">
          <div>
            <p className="label">GeoJSON workshop · polygons to paths</p>
            <h3>From coordinates to clickable provinces</h3>
          </div>
          <div className="pill">
            {converted.length}
            {' converted · '}
            {skipped}
            {' skipped'}
          </div>
        </div>

        <div className="control-row is-wrapping">
          <label className="field is-inline" htmlFor="geojson-mapping">
            <span>Key mapping</span>
            <select
              id="geojson-mapping"
              value={mapping}
              onChange={(event) => setMapping(event.target.value)}
            >
              {Object.entries(MAPPINGS).map(([id, item]) => (
                <option key={id} value={id}>{item.label}</option>
              ))}
            </select>
          </label>
          <label className="field is-inline" htmlFor="geojson-projection">
            <span>Projection</span>
            <select
              id="geojson-projection"
              value={projection}
              onChange={(event) => setProjection(event.target.value)}
            >
              {Object.entries(PROJECTIONS).map(([id, item]) => (
                <option key={id} value={id}>{item.label}</option>
              ))}
            </select>
          </label>
          <label className="toggle-chip">
            <input
              type="checkbox"
              checked={includeUnsupported}
              onChange={(event) => setIncludeUnsupported(event.target.checked)}
            />
            <span>Include unsupported Point</span>
          </label>
        </div>

        <div className="control-row is-wrapping">
          <label className="field is-inline geojson-range" htmlFor="geojson-padding">
            <span>Padding</span>
            <input
              id="geojson-padding"
              type="range"
              min="0"
              max="60"
              step="5"
              value={padding}
              onChange={(event) => setPadding(Number(event.target.value))}
            />
            <strong>{padding}</strong>
          </label>
          <label className="field is-inline geojson-range" htmlFor="geojson-precision">
            <span>Precision</span>
            <input
              id="geojson-precision"
              type="range"
              min="2"
              max="6"
              step="1"
              value={precision}
              onChange={(event) => setPrecision(Number(event.target.value))}
            />
            <strong>{precision}</strong>
          </label>
          <div className="pill subtle">4 usable features · 1 MultiPolygon · 1 hole</div>
        </div>

        {skipped > 0 && (
          <div className="warning-banner" role="status">
            {skipped}
            {' '}
            feature skipped because its geometry is not Polygon or MultiPolygon. The rest of the
            collection still rendered.
          </div>
        )}

        <div className="legend geojson-stats">
          <div className="legend-header">
            <span className="legend-title">Conversion report</span>
            <span className="legend-note">
              {MAPPINGS[mapping].label}
              {' · '}
              {PROJECTIONS[projection].label}
            </span>
          </div>
          <div className="geojson-stat-grid">
            <div className="geo-stat">
              <small>Features</small>
              <strong>{collection.features.length}</strong>
            </div>
            <div className="geo-stat">
              <small>Converted</small>
              <strong>{converted.length}</strong>
            </div>
            <div className="geo-stat">
              <small>Skipped</small>
              <strong>{skipped}</strong>
            </div>
            <div className="geo-stat">
              <small>Output</small>
              <strong>`CityType[]`</strong>
            </div>
          </div>
        </div>

        <div className="map-wrapper">
          <TurkeyMapCore
            id="geojson-workshop"
            data={data}
            hoverable
            showTooltip
            selectionMode="single"
            selectedCity={selectedCity?.id || null}
            onSelectionChange={(next) => setSelectedId(next[0]?.id || null)}
            renderTooltip={renderTooltip}
            ariaLabel="Converted GeoJSON map"
            customStyle={{
              idleColor: '#e2e8f0',
              hoverColor: '#cbd5e1',
              selectedColor: '#0f766e',
              selectedStroke: '#134e4a',
              selectedStrokeWidth: 2,
              focusStroke: '#0d9488',
            }}
          />
        </div>

        <div className="map-footer">
          <div className="pill subtle">Holes survive as interior subpaths</div>
          <div className="pill subtle">MultiPolygon parts stay separate</div>
          <div className="pill subtle">Switch mappings without rewriting SVG paths</div>
        </div>
      </div>

      <aside className="side-panel">
        <div className="panel">
          <p className="label">Selected converted city</p>
          {selectedCity ? (
            <>
              <h3>{selectedCity.name}</h3>
              <p className="meta">
                id
                {' '}
                <strong>{selectedCity.id}</strong>
                {' · plate '}
                {selectedCity.plateNumber}
              </p>
              <div className="geo-stat-grid">
                <div className="geo-stat">
                  <small>Subpaths</small>
                  <strong>{countSubpaths(selectedCity.path)}</strong>
                </div>
                <div className="geo-stat">
                  <small>Path chars</small>
                  <strong>{selectedCity.path.length}</strong>
                </div>
              </div>
              <pre className="code-block geojson-code">
                {JSON.stringify({
                  ...selectedCity,
                  path: `${selectedCity.path.slice(0, 56)}…`,
                }, null, 2)}
              </pre>
            </>
          ) : (
            <div className="empty">No feature converted. Adjust the mapping or sample.</div>
          )}
        </div>

        <div className="panel">
          <p className="label">Sample fixture</p>
          <ul className="hint-list">
            <li>Marmara and Ege are simple Polygons.</li>
            <li>İç Anadolu is a MultiPolygon with two parts.</li>
            <li>Doğu Anadolu has an interior ring (hole).</li>
            <li>An unsupported Point is skipped with a development warning.</li>
            <li>Every usable feature exposes both default and `ADM1_*` properties.</li>
          </ul>
        </div>

        <div className="panel">
          <p className="label">Conversion call</p>
          <pre className="code-block">
            {`import { geoJsonToCities } from 'turkey-map-react/geojson';

const cities = geoJsonToCities(sampleGeoJson, {
  idKey: ${formatKey(MAPPINGS[mapping].keys.idKey)},
  nameKey: ${formatKey(MAPPINGS[mapping].keys.nameKey)},
  plateKey: ${formatKey(MAPPINGS[mapping].keys.plateKey)},
  project: ${projection === 'mercator' ? 'mercator' : 'undefined'},
  padding: ${padding},
  precision: ${precision},
});

<TurkeyMapCore data={{ cities }} />`}
          </pre>
        </div>
      </aside>
    </div>
  );
}

export default GeojsonScenario;
